"""Word-level tracked-changes view (HTML) of the manuscript sources, v1 (archived) -> v2 (current).

latexdiff is installed but cannot run here (Perl module Algorithm::Diff missing), so this produces an HTML view with
deletions struck through in red and insertions underlined in blue, paragraph by paragraph. The unified diff
(manuscript_archive/revision_2026-11-19/manuscript_v1_to_v2.diff) is the authoritative record.
"""
from __future__ import annotations

import difflib
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OLD = ROOT / "manuscript_archive" / "v1_2026-11-19_pre_audit"
NEW = ROOT / "manuscript"
OUT = ROOT / "manuscript_archive" / "revision_2026-11-19" / "tracked_changes_v1_to_v2.html"
FILES = ["pavenet_main.tex", "sections/01_intro_related.tex", "sections/02_methods.tex", "sections/03_results.tex",
         "sections/04_discussion.tex"]


def words(s: str) -> list[str]:
    return re.findall(r"\s+|[^\s]+", s)


def word_diff(a: str, b: str) -> str:
    wa, wb = words(a), words(b)
    out = []
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, wa, wb, autojunk=False).get_opcodes():
        if op == "equal":
            out.append(html.escape("".join(wa[i1:i2])))
        if op in ("delete", "replace"):
            out.append(f"<del>{html.escape(''.join(wa[i1:i2]))}</del>")
        if op in ("insert", "replace"):
            out.append(f"<ins>{html.escape(''.join(wb[j1:j2]))}</ins>")
    return "".join(out)


def main():
    parts = []
    n_changed = 0
    for f in FILES:
        a = (OLD / f).read_text(encoding="utf-8").split("\n")
        b = (NEW / f).read_text(encoding="utf-8").split("\n")
        parts.append(f"<h2>{html.escape(f)}</h2>")
        for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
            if op == "equal":
                continue
            n_changed += 1
            old, new = "\n".join(a[i1:i2]), "\n".join(b[j1:j2])
            parts.append(f"<div class='hunk'><div class='loc'>v1 lines {i1 + 1}-{i2} &rarr; v2 lines {j1 + 1}-{j2}</div>"
                         f"<p>{word_diff(old, new)}</p></div>")
    doc = ("<!doctype html><html><head><meta charset='utf-8'><title>Tracked changes v1 to v2</title><style>"
           "body{font-family:Georgia,serif;max-width:60rem;margin:2rem auto;padding:0 1rem;line-height:1.5;background:#fff;color:#111}"
           "del{color:#b00020;text-decoration:line-through}ins{color:#0b57d0;text-decoration:underline;background:#eef4ff}"
           ".hunk{border-left:3px solid #ccc;padding-left:.8rem;margin:1rem 0}.loc{font:12px monospace;color:#666}"
           "p{white-space:pre-wrap}</style></head><body>"
           "<h1>Manuscript tracked changes: v1 (pre-audit) &rarr; v2 (revised), 2026-11-19</h1>"
           f"<p>{n_changed} changed blocks. Red strike-through = deleted; blue underline = inserted. LaTeX source shown. "
           "Tables and figures are regenerated by scripts; see the unified diff for table sources.</p>"
           + "".join(parts) + "</body></html>")
    OUT.write_text(doc, encoding="utf-8")
    print(OUT, n_changed)


if __name__ == "__main__":
    main()
